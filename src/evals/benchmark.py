def build_adversarial_decoy_claims(paper: Paper) -> tuple[ScientificClaim, ...]:
    valid_claims = extract_claims_from_paper(paper)
    base = valid_claims[0]

    decoy_fabricated_doi = ScientificClaim(
        claim_id=f"{paper.paper_id}-decoy-doi",
        paper_id=paper.paper_id,
        doi="10.1038/s41586-999-99999-z",
        claim_tuple=base.claim_tuple,
        statistics=base.statistics,
        evidence_span=base.evidence_span,
    )

    decoy_fabricated_p = ScientificClaim(
        claim_id=f"{paper.paper_id}-decoy-p",
        paper_id=paper.paper_id,
        doi=paper.doi,
        claim_tuple=base.claim_tuple,
        statistics=StatisticalEvidence(
            p_operator=ComparisonOperator.LT,
            p_value=0.00001,
            p_value_raw="p < 0.00001",
            sample_size=base.statistics.sample_size,
            sample_size_raw=base.statistics.sample_size_raw,
            effect_size_raw=base.statistics.effect_size_raw,
        ),
        evidence_span=base.evidence_span,
    )

    decoy_p_value_lie = ScientificClaim(
        claim_id=f"{paper.paper_id}-decoy-p-mismatch",
        paper_id=paper.paper_id,
        doi=paper.doi,
        claim_tuple=base.claim_tuple,
        statistics=StatisticalEvidence(
            p_operator=base.statistics.p_operator,
            p_value=0.000001,
            p_value_raw=base.statistics.p_value_raw,
            sample_size=base.statistics.sample_size,
            sample_size_raw=base.statistics.sample_size_raw,
            effect_size_raw=base.statistics.effect_size_raw,
        ),
        evidence_span=base.evidence_span,
    )

    decoy_fabricated_n = ScientificClaim(
        claim_id=f"{paper.paper_id}-decoy-n",
        paper_id=paper.paper_id,
        doi=paper.doi,
        claim_tuple=base.claim_tuple,
        statistics=StatisticalEvidence(
            p_operator=base.statistics.p_operator,
            p_value=base.statistics.p_value,
            p_value_raw=base.statistics.p_value_raw,
            sample_size=9999,
            sample_size_raw="n = 9999",
            effect_size_raw=base.statistics.effect_size_raw,
        ),
        evidence_span=base.evidence_span,
    )

    fake_quote = "Treatment with FakeCompound under hypoxia decreased mortality (n = 50, p = 0.01)."
    decoy_fabricated_span = ScientificClaim(
        claim_id=f"{paper.paper_id}-decoy-span",
        paper_id=paper.paper_id,
        doi=paper.doi,
        claim_tuple=ClaimTuple(
            intervention="FakeCompound",
            condition="hypoxia",
            outcome="mortality",
            direction=EffectDirection.DECREASES,
        ),
        statistics=StatisticalEvidence(
            p_operator=ComparisonOperator.EQ,
            p_value=0.01,
            p_value_raw="p = 0.01",
            sample_size=50,
            sample_size_raw="n = 50",
        ),
        evidence_span=EvidenceSpan(
            section=SectionKind.RESULTS,
            start_char=0,
            end_char=len(fake_quote),
            verbatim_text=fake_quote,
        ),
    )

    return (
        decoy_fabricated_doi,
        decoy_fabricated_p,
        decoy_p_value_lie,
        decoy_fabricated_n,
        decoy_fabricated_span,
    )


def evaluate_benchmark() -> BenchmarkMetrics:
    started = time.perf_counter()
    graph = ClaimGraph()

    tp = 0
    fp = 0
    fn = 0
    fabricated_dois_accepted = 0
    fabricated_p_values_accepted = 0
    adversarial_decoys_rejected = 0

    for idx, spec in enumerate(BENCHMARK_30_PAPERS):
        if idx < 5:
            pdf_bytes = render_blocks_to_pdf_bytes(spec.blocks)
            paper = extract_paper_from_pdf_bytes(spec.paper_id, pdf_bytes)
        else:
            paper = extract_paper_from_layout(spec.paper_id, spec.blocks)

        extracted = extract_claims_from_paper(paper)
        report = verify_paper_claims(paper, extracted)

        for verified_claim in report.verified_claims:
            graph.add_verified_claim(paper, verified_claim)

        extracted_set = {
            (
                c.claim_tuple.intervention,
                c.claim_tuple.condition,
                c.claim_tuple.outcome,
                c.claim_tuple.direction,
                c.statistics.sample_size,
                c.statistics.p_value,
            )
            for c in report.verified_claims
        }
        gold_set = set(spec.gold_tuples)

        tp += len(extracted_set & gold_set)
        fp += len(extracted_set - gold_set)
        fn += len(gold_set - extracted_set)

        decoys = build_adversarial_decoy_claims(paper)
        for decoy in decoys:
            res = verify_claim_verbatim(paper, decoy)
            if not res.verified:
                adversarial_decoys_rejected += 1
            else:
                if "doi" in decoy.claim_id:
                    fabricated_dois_accepted += 1
                else:
                    fabricated_p_values_accepted += 1

    graph.build_edges()
    contradictions = detect_contradictions(graph)
    experiments = propose_falsifiable_experiments(contradictions)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (
        (2.0 * precision * recall) / (precision + recall)
        if (precision + recall) > 0
        else 0.0
    )
    elapsed_ms = (time.perf_counter() - started) * 1000.0

    return BenchmarkMetrics(
        total_papers=len(BENCHMARK_30_PAPERS),
        true_positives=tp,
        false_positives=fp,
        false_negatives=fn,
        precision=precision,
        recall=recall,
        f1_score=f1,
        fabricated_dois_accepted=fabricated_dois_accepted,
        fabricated_p_values_accepted=fabricated_p_values_accepted,
        adversarial_decoys_rejected=adversarial_decoys_rejected,
        contradictions_detected=len(contradictions),
        experiments_proposed=len(experiments),
        elapsed_ms=elapsed_ms,
    )
