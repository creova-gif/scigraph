class BenchmarkPaperSpec(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    paper_id: str
    doi: str
    title: str
    authors: tuple[str, ...]
    year: int
    venue: str
    blocks: tuple[LayoutBlock, ...]
    gold_tuples: tuple[tuple[str, str, str, EffectDirection, int, float], ...]


def _make_two_column_spec(
    paper_id: str,
    doi: str,
    title: str,
    authors: tuple[str, ...],
    year: int,
    venue: str,
    abstract_claim: tuple[str, str, str, str, EffectDirection, str, str, int, str, float],
    methods_text: str,
    results_claim: tuple[str, str, str, str, EffectDirection, str, str, int, str, float],
) -> BenchmarkPaperSpec:
    ai, ac, av, ao, adir, acomp, aeff, an, ap_op, ap = abstract_claim
    ri, rc, rv, ro, rdir, rcomp, reff, rn, rp_op, rp = results_claim

    blocks = (
        LayoutBlock(
            page_number=1,
            x0=54.0,
            y0=40.0,
            x1=558.0,
            y1=95.0,
            text=(
                f"Title: {title}\n"
                f"DOI: {doi}\n"
                f"Authors: {', '.join(authors)}\n"
                f"Year: {year}\n"
                f"Venue: {venue}"
            ),
        ),
        LayoutBlock(
            page_number=1,
            x0=54.0,
            y0=105.0,
            x1=558.0,
            y1=170.0,
            text=(
                f"Abstract: Treatment with {ai} under {ac} {av} {ao} "
                f"compared with {acomp} ({aeff}; n = {an}, p {ap_op} {ap})."
            ),
        ),
        LayoutBlock(
            page_number=1,
            x0=54.0,
            y0=190.0,
            x1=292.0,
            y1=340.0,
            text=f"Methods: {methods_text}",
        ),
        LayoutBlock(
            page_number=1,
            x0=320.0,
            y0=190.0,
            x1=558.0,
            y1=340.0,
            text=(
                f"Results: Treatment with {ri} under {rc} {rv} {ro} "
                f"compared with {rcomp} ({reff}; n = {rn}, p {rp_op} {rp})."
            ),
        ),
    )
    return BenchmarkPaperSpec(
        paper_id=paper_id,
        doi=doi,
        title=title,
        authors=authors,
        year=year,
        venue=venue,
        blocks=blocks,
        gold_tuples=(
            (ai, ac, ao, adir, an, ap),
            (ri, rc, ro, rdir, rn, rp),
        ),
    )


